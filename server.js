// سؤال من جدول: الصح بقيمته، والغلط ياخذ قيمة صف ثاني تسمح فيه okDecoy
function tableQ(rows, want, say, okDecoy = () => true) {
  const row = pick(rows);
  if (want) return [say(row[0], row[1]), true];
  const pool = rows.filter((r) => r[1] !== row[1] && okDecoy(row, r));
  if (!pool.length) return [say(row[0], row[1]), true];
  return [say(row[0], pick(pool)[1]), false];
}

// ترتيب (كواكب، شهور): الغلط يكون قريب من الترتيب الصح عشان يحيّر
function orderQ(list, want, say) {
  const i = rnd(list.length);
  const j = want ? i : pick([i - 2, i - 1, i + 1, i + 2].filter((k) => k >= 0 && k < list.length));
  return [say(list[i], ORDINALS[j]), want];
}

